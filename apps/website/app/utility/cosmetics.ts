interface CosmeticCatalogueEntry {
	nameKeys: string[] | null;
	sources: CosmeticSource[];
}

function addCatalogueItems(
	catalogue: Map<Cosmetic, CosmeticCatalogueEntry>,
	items: Iterable<Item>,
	target: CatalogueSearchTargetWithoutEventFamily,
) {
	for (const item of items) {
		for (const cosmetic of item.cosmetics) {
			let entry = catalogue.get(cosmetic);

			if (!entry) {
				entry = { nameKeys: null, sources: [] };
				catalogue.set(cosmetic, entry);
			}

			if (entry.nameKeys === null && !item.translation.key.startsWith(UNNAMED_TRANSLATION_PREFIX)) {
				const cosmeticNameKey = `cosmetic-names.${cosmetic}`;

				entry.nameKeys =
					item.translation.key === cosmeticNameKey
						? [cosmeticNameKey]
						: [cosmeticNameKey, item.translation.key];
			}

			if (!entry.sources.some((source) => source.target === target)) {
				entry.sources.push({ item, target });
			}
		}
	}
}

function cosmeticCatalogue() {
	const catalogue = new Map<Cosmetic, CosmeticCatalogueEntry>();

	for (const spirit of spirits().values()) {
		addCatalogueItems(catalogue, friendshipTreeToItems(spirit.displayFriendshipTree), {
			type: CatalogueSearchType.Spirit,
			spirit,
		});
	}

	for (const season of skySeasons().values()) {
		addCatalogueItems(catalogue, season.items, { type: CatalogueSearchType.Season, season });
	}

	for (const event of skyEvents().values()) {
		addCatalogueItems(catalogue, event.offer, { type: CatalogueSearchType.Event, event });
	}

	for (const [collection, items] of CATALOGUE_COLLECTION_ITEMS) {
		addCatalogueItems(catalogue, items, { type: CatalogueSearchType.Collection, collection });
	}

	return catalogue;
}

interface ReleasedCosmetics {
	readonly anchorTargets: ReadonlyMap<string, CosmeticAnchorTarget>;
	readonly catalogue: ReadonlyMap<Cosmetic, Readonly<CosmeticCatalogueEntry>>;
	readonly groups: readonly (readonly CosmeticsSection[])[];
	readonly sections: readonly CosmeticsSection[];
}

export function releasedCosmetics(): ReleasedCosmetics {
	const catalogue = cosmeticCatalogue();

	const sections = ALL_COSMETICS_SECTIONS.map(({ heading, icon, table, tiles }) => ({
		heading,
		icon,
		table,
		tiles: tiles.filter(
			({ cosmetic }) => catalogue.has(cosmetic) || UNSOURCED_COSMETICS.has(cosmetic),
		),
	}));

	const groups = COSMETICS_GROUP_TABLES.map((tables) =>
		tables.map((table) => sections.find((section) => section.table === table)!),
	);

	const anchorTargets = new Map<string, CosmeticAnchorTarget>();

	for (const [groupIndex, groupSections] of groups.entries()) {
		for (const section of groupSections) {
			for (const tile of section.tiles) {
				anchorTargets.set(tile.anchor, { groupIndex, table: section.table, tile });
			}
		}
	}

	return { anchorTargets, catalogue, groups, sections };
}

export function cosmeticName(nameKeys: string[], i18n: I18n, t: TFunction) {
	const translatedNameKey = nameKeys.find((nameKey) =>
		i18n.getResource(i18n.language, "general", nameKey),
	);

	return t(translatedNameKey ?? nameKeys, { ns: "general" });
}

export function catalogueLocation(target: CatalogueSearchTargetWithoutEventFamily, t: TFunction) {
	const query = catalogueTargetQuery(target);

	switch (target.type) {
		case CatalogueSearchType.Season:
			return {
				type: target.type,
				query,
				emoji: SeasonIdToSeasonalEmoji[target.season.id],
				name: t(`seasons.${target.season.id}`, { ns: "general" }),
				detail: t("season", { ns: "general" }),
				pageURL: null,
				wikiURL: t(`season-wiki.${target.season.id}`, { ns: "general" }),
			};
		case CatalogueSearchType.Event:
			return {
				type: target.type,
				query,
				emoji: EventIdToEventTicketEmoji[target.event.id],
				name: t(target.event.name, { ns: "general" }),
				detail: String(target.event.start.year),
				pageURL: null,
				wikiURL: t(`event-wiki.${target.event.id}`, { ns: "general" }),
			};
		case CatalogueSearchType.Spirit: {
			const { spirit } = target;
			const seasonal = spirit.isSeasonalSpirit() || spirit.isGuideSpirit();

			return {
				type: target.type,
				query,
				emoji: seasonal ? SeasonIdToSeasonalEmoji[spirit.seasonId] : null,
				name: t(`spirits.${spirit.id}`, { ns: "general" }),
				detail: t(spiritOriginTranslationKey(spirit), { ns: "general" }),
				pageURL: `/spirits?spirit=${spirit.id}`,
				wikiURL: t(`spirit-wiki.${spirit.id}`, { ns: "general" }),
			};
		}
		case CatalogueSearchType.Collection:
			return {
				type: target.type,
				query,
				emoji: null,
				name: t(CatalogueCollectionToLocaleKey[target.collection]),
				detail: null,
				pageURL: null,
				wikiURL: null,
			};
	}
}

function itemPricing(item: Item) {
	const costs = item.cost ? sumCosts([item.cost]) : [];

	return {
		costs,
		seasonPass: item.seasonPass && !costs.some((cost) => cost.type === "seasonalHearts"),
	};
}

export function itemOfferTile(
	item: Item,
	{ name, owned, seasonPassEmoji }: Pick<OfferTile, "name" | "owned" | "seasonPassEmoji">,
): OfferTile {
	return {
		costs: itemPricing(item).costs,
		name,
		owned,
		seasonPassEmoji,
		tile: {
			anchor: cosmeticAnchor(item.cosmeticDisplay),
			cosmetic: item.cosmeticDisplay,
			emoji: itemEmoji(item) ?? MISCELLANEOUS_EMOJIS.QuestionMark,
		},
	};
}

export function cosmeticSources(entry: CosmeticCatalogueEntry | undefined, t: TFunction) {
	return (
		entry?.sources.map(({ item, target }) =>
			Object.assign(catalogueLocation(target, t), itemPricing(item)),
		) ?? []
	);
}
