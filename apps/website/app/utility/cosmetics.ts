function emojiCosmetics() {
	const cosmetics = new Map<Emoji["id"], Cosmetic[]>();

	for (const [cosmetic, emoji] of Object.entries(CosmeticToEmoji)) {
		if (!emoji) {
			continue;
		}

		const emojiCosmeticList = cosmetics.get(emoji.id);

		if (emojiCosmeticList) {
			emojiCosmeticList.push(Number(cosmetic));
		} else {
			cosmetics.set(emoji.id, [Number(cosmetic)]);
		}
	}

	return cosmetics;
}

const EMOJI_COSMETICS = emojiCosmetics();

export function cosmeticAnchor(cosmetic: Cosmetic | string) {
	return `${COSMETIC_ANCHOR_PREFIX}${cosmetic}`;
}

function addCosmeticTiles(tiles: CosmeticTileData[], emoji: Emoji) {
	for (const cosmetic of EMOJI_COSMETICS.get(emoji.id) ?? []) {
		tiles.push({ anchor: cosmeticAnchor(cosmetic), cosmetic, emoji });
	}
}

const ALL_COSMETICS_SECTIONS = COSMETICS_ORDER.map(({ heading, icon, order, table }) => {
	const emojis: Readonly<Record<string, Emoji>> = EMOJIS[table];
	const listed = new Set<string>();
	const tiles: CosmeticTileData[] = [];

	for (const emoji of order) {
		listed.add(emoji.id);
		addCosmeticTiles(tiles, emoji);
	}

	for (const emoji of Object.values(emojis)) {
		if (!listed.has(emoji.id)) {
			addCosmeticTiles(tiles, emoji);
		}
	}

	return { heading, icon, table, tiles };
});

